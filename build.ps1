[CmdletBinding()]
param(
    [switch]$Test,
    [switch]$ClipboardTest,
    [string]$Version,
    [switch]$WriteVersionOnly
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$projectRoot = $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($Version)) {
    $Version = [System.IO.File]::ReadAllText((Join-Path $projectRoot 'VERSION')).Trim()
}
$number = '(?:0|[1-9][0-9]*)'
$preIdentifier = '(?:0|[1-9][0-9]*|[0-9]*[A-Za-z-][0-9A-Za-z-]*)'
$versionPattern = '\Av?(?<version>(?<major>' + $number + ')\.(?<minor>' + $number + ')\.(?<patch>' + $number + ')' +
    '(?:-' + $preIdentifier + '(?:\.' + $preIdentifier + ')*)?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?)\z'
$versionMatch = [regex]::Match($Version, $versionPattern)
if (!$versionMatch.Success) { throw 'Version must be SemVer, optionally prefixed with v (for example 0.1.5 or v0.2.0-rc.1).' }
$informationalVersion = $versionMatch.Groups['version'].Value
foreach ($part in @('major', 'minor', 'patch')) {
    $partValue = 0
    if (![int]::TryParse($versionMatch.Groups[$part].Value, [ref]$partValue) -or $partValue -gt 65534) {
        throw 'Version core components must be between 0 and 65534 for .NET assembly metadata.'
    }
}
$fileVersion = $versionMatch.Groups['major'].Value + '.' + $versionMatch.Groups['minor'].Value + '.' + $versionMatch.Groups['patch'].Value + '.0'
$generatedDirectory = Join-Path $projectRoot 'obj'
[System.IO.Directory]::CreateDirectory($generatedDirectory) | Out-Null
$versionSourcePath = Join-Path $generatedDirectory 'Screenline.AssemblyVersion.cs'
$versionSource = '// Generated by build.ps1; do not edit.' + "`r`n" +
    '[assembly: System.Reflection.AssemblyVersion("' + $fileVersion + '")]' + "`r`n" +
    '[assembly: System.Reflection.AssemblyFileVersion("' + $fileVersion + '")]' + "`r`n" +
    '[assembly: System.Reflection.AssemblyInformationalVersion("' + $informationalVersion + '")]' + "`r`n"
[System.IO.File]::WriteAllText($versionSourcePath, $versionSource, (New-Object System.Text.UTF8Encoding($false)))
if ($WriteVersionOnly) { return }
$frameworkPath = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319'
$compilerPath = Join-Path $frameworkPath 'csc.exe'
if (!(Test-Path -LiteralPath $compilerPath)) { throw 'Windows .NET Framework 4.8 is required.' }
$references = @('System.dll','System.Core.dll','System.Net.Http.dll','System.Runtime.Serialization.dll','System.Drawing.dll','System.Windows.Forms.dll','System.Xaml.dll') | ForEach-Object { '/reference:' + (Join-Path $frameworkPath $_) }
$references += @('WindowsBase.dll','PresentationCore.dll','PresentationFramework.dll') | ForEach-Object { '/reference:' + (Join-Path (Join-Path $frameworkPath 'WPF') $_) }
$sourceFiles = Get-ChildItem -LiteralPath (Join-Path $projectRoot 'src') -Filter '*.cs' | ForEach-Object { $_.FullName }
$sourceFiles += $versionSourcePath
$arguments = @('/nologo','/target:winexe','/platform:x64','/optimize+','/warn:4','/codepage:65001',('/win32manifest:' + (Join-Path $projectRoot 'app.manifest')),('/out:' + (Join-Path $projectRoot 'Screenline.exe')))
& $compilerPath @arguments @references @sourceFiles
if ($LASTEXITCODE -ne 0) { throw 'Build failed.' }
Write-Output ('Version ' + $informationalVersion)
Write-Output ('Built ' + (Join-Path $projectRoot 'Screenline.exe'))
if ($Test) {
    $testOutputPath = Join-Path $projectRoot 'tests\results'
    $process = Start-Process -FilePath (Join-Path $projectRoot 'Screenline.exe') -ArgumentList @('--self-test',('"' + $testOutputPath + '"')) -Wait -PassThru -WindowStyle Hidden
    Get-Content -LiteralPath (Join-Path $testOutputPath 'report.txt')
    if ($process.ExitCode -ne 0) { throw 'Self tests failed.' }
}
if ($ClipboardTest) {
    $clipboardOutputPath = Join-Path $projectRoot 'tests\clipboard-results'
    $process = Start-Process -FilePath (Join-Path $projectRoot 'Screenline.exe') -ArgumentList @('--clipboard-test',('"' + $clipboardOutputPath + '"')) -Wait -PassThru -WindowStyle Hidden
    Get-Content -LiteralPath (Join-Path $clipboardOutputPath 'report.txt')
    if ($process.ExitCode -ne 0) { throw 'Clipboard integration tests failed.' }
}

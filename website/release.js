// The website accepts download metadata only after checking the same signed
// manifest as the Windows application. No URL is accepted from the manifest.
export const RELEASE_BASE_URL = "https://screenline-updates-xiaogao007.oss-cn-hangzhou.aliyuncs.com/screenline/";
const MAX_ENVELOPE = 128 * 1024;
const MAX_PAYLOAD = 64 * 1024;
const MAX_KEY = 4 * 1024;
const TIMEOUT_MS = 8000;
const STABLE_TAG = /^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/;
const EXPECTED_FIELDS = ["schema", "tag", "installer", "size", "sha256", "notes"];
const decoder = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

export class ReleaseError extends Error {
  constructor(code) {
    super(code);
    this.name = "ReleaseError";
    this.code = code;
  }
}

function reject(code = "invalid") {
  throw new ReleaseError(code);
}

function exactFields(value, fields) {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    && Object.keys(value).length === fields.length
    && fields.every((field) => Object.hasOwn(value, field));
}

function hasUnpairedSurrogate(text) {
  for (let index = 0; index < text.length; index += 1) {
    const code = text.charCodeAt(index);
    if (code >= 0xd800 && code <= 0xdbff) {
      const next = text.charCodeAt(++index);
      if (!(next >= 0xdc00 && next <= 0xdfff)) return true;
    } else if (code >= 0xdc00 && code <= 0xdfff) return true;
  }
  return false;
}

// These two protocol objects are deliberately flat. This parser rejects
// duplicate properties and nested values instead of JSON.parse's last-key-wins.
export function parseFlatObject(text) {
  let offset = 0;
  const whitespace = () => { while (/[\t\r\n ]/.test(text[offset] || "\0")) offset += 1; };
  const string = () => {
    const match = /^"(?:[^"\\\u0000-\u001f]|\\(?:["\\/bfnrt]|u[0-9a-fA-F]{4}))*"/.exec(text.slice(offset));
    if (!match) reject();
    offset += match[0].length;
    const result = JSON.parse(match[0]);
    if (hasUnpairedSurrogate(result)) reject();
    return result;
  };
  const result = Object.create(null);
  whitespace();
  if (text[offset++] !== "{") reject();
  whitespace();
  if (text[offset] === "}") offset += 1;
  else {
    while (true) {
      whitespace();
      const key = string();
      if (Object.hasOwn(result, key)) reject();
      whitespace();
      if (text[offset++] !== ":") reject();
      whitespace();
      let value;
      if (text[offset] === '"') value = string();
      else {
        const number = /^-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?/.exec(text.slice(offset));
        if (!number) reject();
        offset += number[0].length;
        value = Number(number[0]);
        if (!Number.isFinite(value)) reject();
      }
      result[key] = value;
      whitespace();
      const delimiter = text[offset++];
      if (delimiter === "}") break;
      if (delimiter !== ",") reject();
    }
  }
  whitespace();
  if (offset !== text.length) reject();
  return result;
}

function decodeBase64(value, limit) {
  if (typeof value !== "string" || value.length === 0 || value.length > 4 * Math.ceil(limit / 3)
      || !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(value)) reject();
  let raw;
  try { raw = atob(value); } catch { reject(); }
  if (raw.length > limit || btoa(raw) !== value) reject();
  return Uint8Array.from(raw, (character) => character.charCodeAt(0));
}

function decodeBase64Url(value, limit) {
  if (typeof value !== "string" || !/^[A-Za-z0-9_-]+$/.test(value)) reject();
  const standard = value.replaceAll("-", "+").replaceAll("_", "/");
  return decodeBase64(standard.padEnd(Math.ceil(standard.length / 4) * 4, "="), limit);
}

export function validatePublicKey(value) {
  if (!exactFields(value, ["kty", "n", "e", "alg"])
      || value.kty !== "RSA" || value.alg !== "RS256"
      || value.e !== "AQAB") reject("key");
  const modulus = decodeBase64Url(value.n, 1024);
  // Public key generated by the release tooling: 2048–8192 bits, exponent 65537.
  if (modulus.length < 256 || modulus[0] < 128) reject("key");
  return value;
}

export function validateManifest(value) {
  if (!exactFields(value, EXPECTED_FIELDS) || value.schema !== 1
      || typeof value.tag !== "string" || value.tag.length > 256 || !STABLE_TAG.test(value.tag)
      || value.installer !== `Screenline-${value.tag}-windows-x64-setup.exe`
      || !Number.isSafeInteger(value.size) || value.size < 2 || value.size > 256 * 1024 * 1024
      || typeof value.sha256 !== "string" || !/^[0-9a-f]{64}$/.test(value.sha256)
      || typeof value.notes !== "string" || value.notes.length > 16384
      || /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f-\u009f]/.test(value.notes)
      || hasUnpairedSurrogate(value.notes)) reject();
  return Object.freeze(value);
}

export async function verifyReleaseEnvelope(bytes, publicKey, cryptoProvider = globalThis.crypto) {
  if (!(bytes instanceof Uint8Array) || bytes.length > MAX_ENVELOPE || bytes.length === 0) reject();
  if (!cryptoProvider?.subtle) reject("unsupported");
  const envelope = parseFlatObject(decoder.decode(bytes));
  if (!exactFields(envelope, ["payload", "signature"])) reject();
  const payload = decodeBase64(envelope.payload, MAX_PAYLOAD);
  const signature = decodeBase64(envelope.signature, 1024);
  const jwk = validatePublicKey(publicKey);
  const key = await cryptoProvider.subtle.importKey("jwk", jwk,
    { name: "RSASSA-PKCS1-v1_5", hash: "SHA-256" }, false, ["verify"]);
  if (!await cryptoProvider.subtle.verify("RSASSA-PKCS1-v1_5", key, signature, payload)) reject("signature");
  // Decode and interpret the payload only after its exact bytes are verified.
  return validateManifest(parseFlatObject(decoder.decode(payload)));
}

export function releaseLinks(manifest) {
  validateManifest(manifest);
  const root = `${RELEASE_BASE_URL}releases/${encodeURIComponent(manifest.tag)}/`;
  return Object.freeze({
    installer: root + encodeURIComponent(manifest.installer),
    portable: root + encodeURIComponent(`Screenline-${manifest.tag}-windows-x64.zip`),
    source: root + encodeURIComponent(`Screenline-${manifest.tag}-source.zip`),
    checksums: root + "SHA256SUMS.txt",
  });
}

export async function readBoundedResponse(response, maximum) {
  if (!response.ok || response.status !== 200 || response.redirected) reject("network");
  const declaredLength = response.headers.get("Content-Length");
  if (declaredLength !== null && (!/^[0-9]+$/.test(declaredLength) || Number(declaredLength) > maximum)) reject();
  if (!response.body?.getReader) reject("unsupported");
  const reader = response.body.getReader();
  const chunks = [];
  let length = 0;
  try {
    while (true) {
      const part = await reader.read();
      if (part.done) break;
      length += part.value.byteLength;
      if (length > maximum) { await reader.cancel(); reject(); }
      chunks.push(part.value);
    }
  } finally { reader.releaseLock(); }
  const result = new Uint8Array(length);
  let offset = 0;
  for (const chunk of chunks) { result.set(chunk, offset); offset += chunk.byteLength; }
  return result;
}

export async function fetchVerifiedRelease({ fetcher = globalThis.fetch, cryptoProvider = globalThis.crypto,
  baseUrl = import.meta.url, timeout = TIMEOUT_MS } = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeout);
  const options = { signal: controller.signal, cache: "no-store", credentials: "omit", redirect: "error" };
  let stage = "fetch";
  try {
    const get = async (path, maximum) => {
      try { return await readBoundedResponse(await fetcher(new URL(path, baseUrl), options), maximum); }
      catch (error) {
        if (error && Object.isExtensible(error)) error.releaseStage = path.includes("latest.json") ? "fetch-manifest" : "fetch-key";
        throw error;
      }
    };
    const [envelope, keyBytes] = await Promise.all([
      get("./releases/latest.json", MAX_ENVELOPE), get("./release-key.json", MAX_KEY),
    ]);
    stage = "parse-key";
    const jwk = parseFlatObject(decoder.decode(keyBytes));
    stage = "verify";
    const manifest = await verifyReleaseEnvelope(envelope, jwk, cryptoProvider);
    if (controller.signal.aborted) reject("network");
    return manifest;
  } catch (error) {
    if (error && Object.isExtensible(error) && !error.releaseStage) error.releaseStage = stage;
    throw error;
  } finally {
    clearTimeout(timer);
    controller.abort();
  }
}

function setText(documentRoot, selector, text) {
  documentRoot.querySelectorAll(selector).forEach((element) => { element.textContent = text; });
}

export function initReleaseClient(documentRoot = globalThis.document, load = fetchVerifiedRelease) {
  const status = documentRoot.getElementById("release-status");
  const notes = documentRoot.getElementById("release-notes");
  const retry = documentRoot.getElementById("retry-release");
  if (!status || !notes || !retry) return null;
  let pending = false;
  const anchors = [...documentRoot.querySelectorAll("a[data-download]")];
  const dates = [...documentRoot.querySelectorAll('[data-release="date"]')];
  const reset = () => {
    anchors.forEach((anchor) => { anchor.href = "#download"; anchor.setAttribute("aria-disabled", "true"); });
    dates.forEach((date) => { date.hidden = true; });
  };
  const refresh = async () => {
    if (pending) return;
    pending = true;
    reset();
    retry.disabled = true;
    retry.hidden = true;
    status.dataset.state = "loading";
    delete status.dataset.error;
    delete status.dataset.errorStage;
    status.textContent = "正在获取版本信息并校验发布签名…";
    notes.textContent = "校验通过后，这里会显示对应版本的更新说明。";
    setText(documentRoot, '[data-release="version"]', "版本查询中");
    setText(documentRoot, '[data-release="size"]', "大小待确认");
    let stage = "load";
    try {
      const manifest = await load();
      stage = "render";
      const links = releaseLinks(manifest);
      anchors.forEach((anchor) => {
        if (!Object.hasOwn(links, anchor.dataset.download)) return;
        const link = links[anchor.dataset.download];
        anchor.href = link;
        anchor.removeAttribute("aria-disabled");
      });
      setText(documentRoot, '[data-release="version"]', manifest.tag);
      setText(documentRoot, '[data-release="size"]', `${new Intl.NumberFormat("zh-CN", { maximumFractionDigits: 1 }).format(manifest.size / 1024 / 1024)} MB`);
      notes.textContent = manifest.notes || "此版本未提供更新说明。";
      status.dataset.state = "success";
      status.textContent = "发布签名已验证，可使用国内 OSS 下载。";
    } catch (error) {
      // Keep a bounded diagnostic for support; never log the signed content.
      const diagnostic = error instanceof ReleaseError ? error.code
        : error?.name === "AbortError" ? "timeout"
          : error?.name === "TypeError" ? "network-or-runtime" : "runtime";
      status.dataset.error = diagnostic;
      status.dataset.errorStage = error?.releaseStage || stage;
      console.warn("Screenline release check failed:", diagnostic,
        status.dataset.errorStage, error instanceof Error ? error.name : "Error");
      reset();
      setText(documentRoot, '[data-release="version"]', "版本暂不可用");
      setText(documentRoot, '[data-release="size"]', "—");
      notes.textContent = "暂时无法读取已验证的更新说明。";
      status.dataset.state = "error";
      status.textContent = error instanceof ReleaseError && error.code === "unsupported"
        ? "浏览器无法校验发布签名。请使用 GitHub 备用下载。"
        : "版本信息获取或签名校验失败。请重试，或使用 GitHub 备用下载。";
      retry.hidden = false;
    } finally {
      pending = false;
      retry.disabled = false;
    }
  };
  retry.addEventListener("click", refresh);
  void refresh();
  return { refresh };
}

if (typeof document !== "undefined") initReleaseClient();
